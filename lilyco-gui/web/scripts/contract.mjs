import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { compile } from "json-schema-to-typescript";

const file = new URL("../src/contract.ts", import.meta.url);
const schema = execFileSync("cargo", [
  "run", "--quiet", "--locked", "-p", "lilyco-core",
  "--features", "ui-schema", "--example", "ui_contract",
], { cwd: new URL("../../../", import.meta.url), encoding: "utf8" });
function normalize(node) {
  if (node === true) return { tsType: "unknown" };
  if (Array.isArray(node)) return node.map(normalize);
  if (!node || typeof node !== "object") return node;
  const output = { ...node };
  for (const key of ["properties", "definitions"]) {
    if (output[key]) output[key] = Object.fromEntries(Object.entries(output[key]).map(([name, field]) => [name, normalize(field)]));
  }
  for (const key of ["oneOf", "anyOf", "allOf", "items", "additionalProperties"]) {
    if (Object.hasOwn(output, key)) output[key] = normalize(output[key]);
  }
  if (Object.keys(output).every(key => ["description", "default", "title"].includes(key))) output.tsType = "unknown";
  return output;
}
const types = await compile(normalize(JSON.parse(schema)), "UiContract", {
  bannerComment: "// Generated by pnpm contract from lilyco-core. Edit the Rust contract.",
  unknownAny: true,
  declareExternallyReferenced: true,
});
if (process.argv.includes("--check")) {
  if (readFileSync(file, "utf8") !== types) throw new Error("Stale UI contract. Run pnpm contract.");
} else {
  writeFileSync(file, types);
}
