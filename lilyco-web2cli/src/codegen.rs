//! 将 `WebCliSpec` 生成为独立的 Rust `lilyco` 应用 crate（可直接编译为四端原生二进制）。

use std::fs;
use std::path::Path;

use lilyco::__core::error::AppError;

use crate::spec::{sanitize_ident, WebCliSpec};

pub struct GeneratedCrate {
    pub crate_name: String,
    pub cargo_toml: String,
    pub main_rs: String,
    pub spec_json: String,
}

pub fn generate_crate(
    spec: &WebCliSpec,
    crate_name_override: Option<&str>,
) -> Result<GeneratedCrate, AppError> {
    let crate_name = sanitize_ident(crate_name_override.unwrap_or(&spec.name), "web-cli-app");
    let bin_name = crate_name.clone();
    let spec_json = spec.to_json_pretty()?;

    let cargo_toml = format!(
        r#"[package]
name = "{crate_name}"
version = "0.1.0"
edition = "2021"

[[bin]]
name = "{bin_name}"
path = "src/main.rs"

[dependencies]
lilyco = {{ version = "0.3", features = ["full"] }}
lilyco-web2cli = {{ version = "0.3" }}
"#
    );

    let main_rs = format!(
        r#"//! Auto-generated by `lilyco-web2cli` for {url}

use std::sync::Arc;
use lilyco_web2cli::{{SessionManager, WebCliSpec}};

const SPEC_JSON: &str = include_str!("../spec.webcli.json");

fn main() {{
    let spec = WebCliSpec::from_str_auto(SPEC_JSON).expect("valid embedded WebCliSpec");
    let session = Arc::new(SessionManager::new("{crate_name}"));
    let backend = lilyco::detect_registry_backend();
    let policy: Arc<dyn lilyco::__core::safety::SafetyPolicy> = match backend {{
        lilyco::Backend::Mcp => Arc::new(lilyco::__core::safety::DenyElevated),
        _ => Arc::new(lilyco::__core::safety::Interactive),
    }};
    let registry = spec
        .to_registry(session, Some(policy))
        .expect("build registry from WebCliSpec");
    lilyco::run_registry_with("{bin_name}", registry, backend);
}}
"#,
        url = spec.base_url
    );

    Ok(GeneratedCrate {
        crate_name,
        cargo_toml,
        main_rs,
        spec_json,
    })
}

pub fn write_generated_crate(gen: &GeneratedCrate, out_dir: &Path) -> Result<(), AppError> {
    let src_dir = out_dir.join("src");
    fs::create_dir_all(&src_dir)
        .map_err(|e| AppError::Runtime(format!("创建输出目录失败: {e}")))?;
    fs::write(out_dir.join("Cargo.toml"), &gen.cargo_toml)
        .map_err(|e| AppError::Runtime(format!("写入 Cargo.toml 失败: {e}")))?;
    fs::write(out_dir.join("spec.webcli.json"), &gen.spec_json)
        .map_err(|e| AppError::Runtime(format!("写入 spec.webcli.json 失败: {e}")))?;
    fs::write(src_dir.join("main.rs"), &gen.main_rs)
        .map_err(|e| AppError::Runtime(format!("写入 src/main.rs 失败: {e}")))?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::discover::discover_from_html;

    #[test]
    fn generates_standalone_rust_crate() {
        let spec = discover_from_html(
            "https://example.com/",
            "<html><body><form action=\"/s\"><input name=\"q\"></form></body></html>",
        );
        let dir = tempfile::tempdir().unwrap();
        let gen = generate_crate(&spec, Some("example-cli")).unwrap();
        write_generated_crate(&gen, dir.path()).unwrap();
        assert!(dir.path().join("Cargo.toml").is_file());
        assert!(dir.path().join("spec.webcli.json").is_file());
        assert!(dir.path().join("src/main.rs").is_file());
    }
}
